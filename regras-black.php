            <a href="politica.php">Política de Privacidade da Vésteme Modas</a>, que
            integra este regulamento para todos os fins.
        </p>
        <p>
            Recomenda-se a leitura atenta da Política de Privacidade antes da conclusão
            do cadastro e do envio do carrinho, especialmente quanto a:
        </p>
        <ul>
            <li>finalidades de uso dos dados (campanha, relacionamento e marketing);</li>
            <li>direitos dos titulares e formas de exercício;</li>
            <li>compartilhamento com terceiros e transferências internacionais;</li>
            <li>prazo de retenção e medidas de segurança.</li>
        </ul>
    </section>

