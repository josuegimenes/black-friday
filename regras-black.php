    <section>
        <h2>5. Mecânica da campanha e formação da fila</h2>
        <h3>5.1. Cadastro e montagem do carrinho</h3>
        <p>
            Para participar, o interessado deverá:
        </p>
        <ol>
            <li>
                Acessar a landing page oficial da campanha;
            </li>
            <li>
                Selecionar as categorias e produtos desejados, nas quantidades e variações
                (cor, tamanho) disponibilizadas na campanha;
            </li>
            <li>
                Preencher corretamente seus dados de contato (nome, e-mail e WhatsApp)
                e confirmar o envio do formulário, sem realização de pagamento neste momento;
            </li>
            <li>
                Confirmar ciência das regras da campanha e da Política de Privacidade,
                quando solicitado na própria landing.
            </li>
        </ol>
        <p>
            O envio do carrinho <strong>não caracteriza pedido em firme nem reserva
            automática de estoque</strong>, mas sim um <strong>registro de interesse</strong>
            que servirá de base para a organização da fila de atendimento e para o envio
            posterior do link de pagamento.
        </p>

        <h3>5.2. Fila e prioridade de atendimento</h3>
        <p>
            A prioridade de atendimento na campanha será, em regra, definida pela
            <strong>data e horário de envio do formulário/carrinho</strong>, conforme registrado
            nos sistemas da Vésteme, observado o horário de Brasília.
        </p>
        <p>
            Para identificar o participante na fila, a Vésteme utilizará os dados fornecidos
            (nome, e-mail, WhatsApp e demais informações eventualmente solicitadas).
        </p>
        <p>
            O mesmo participante poderá enviar novos carrinhos ao longo da campanha.
            A Vésteme poderá:
        </p>
        <ul>
            <li>
                considerar para efeitos de liberação o <strong>último pedido enviado</strong>
                com o mesmo e-mail/WhatsApp, cancelando ou desconsiderando pedidos anteriores
                que ainda não tenham sido processados; ou
            </li>
            <li>
                tratar os diferentes envios como pedidos distintos, desde que operacionalmente
                viável, com informação ao cliente no momento da liberação.
            </li>
        </ul>
        <p>
            A política efetiva (uso do último pedido ou pedidos separados) poderá ser ajustada
            pela Vésteme a cada edição, conforme capacidades técnicas e volume de participantes,
            sempre buscando manter a organização da fila e a clareza nas comunicações.
        </p>

        <h3>5.3. Confirmação via canais oficiais</h3>
        <p>
            O participante poderá ser convidado a ingressar em <strong>grupo oficial de WhatsApp</strong>
            ou a manter contato com a Vésteme por canal institucional para:
        </p>
        <ul>
            <li>acompanhar comunicados gerais da campanha;</li>
            <li>receber avisos de liberação do seu pedido;</li>
            <li>tirar dúvidas e ajustar detalhes de pagamento e entrega.</li>
        </ul>
        <p>
            O ingresso ou permanência em grupo de WhatsApp, por si só, não garante prioridade
            superior àquela definida pela data/hora de envio do formulário, mas pode ser
            utilizado para agilizar comunicações e esclarecimentos.
        </p>
    </section>

    <section>
        <h2>6. Envio do link de pagamento, reserva e expiração</h2>
        <p>
            Quando chegar a vez do participante na fila, a Vésteme poderá:
        </p>
        <ul>
            <li>
                validar a disponibilidade dos itens selecionados e eventuais substituições;
            </li>
            <li>
                ajustar valores e condições promocionais aplicáveis ao pedido;
            </li>
            <li>
                enviar um <strong>link de pagamento</strong> por canal oficial (por exemplo,
                WhatsApp ou e-mail).
            </li>
        </ul>
        <p>
            O <strong>envio do link de pagamento não garante, por si só, a reserva definitiva
            dos produtos</strong>. A disponibilidade final dependerá da efetivação do pagamento
            e da confirmação pelos sistemas de cobrança.
        </p>
        <p>
            O link de pagamento poderá conter um prazo específico de validade, que,
            como regra geral, será de até <strong>2 (duas) horas</strong> contadas do
            seu envio, salvo indicação diversa no próprio link ou mensagem.
        </p>
        <p>
            Decorrido o prazo sem pagamento:
        </p>
        <ul>
            <li>
                a Vésteme poderá considerar aquele pedido como <strong>não concluído</strong>,
                liberando os produtos correspondentes para outros participantes; e
            </li>
            <li>
                o participante poderá ser reposicionado para o <strong>fim da fila</strong>,
                caso ainda deseje aproveitar a campanha, sujeitando-se à nova disponibilidade
                de estoque e condições vigentes.
            </li>
        </ul>
        <p>
            Somente com o <strong>pagamento efetivamente aprovado</strong> (Pix confirmado
            ou transação de cartão de crédito autorizada) é que o pedido será considerado
            firme e o estoque correspondente será efetivamente reservado ao cliente.
        </p>
    </section>

    <section>
        <h2>7. Indisponibilidade de itens e substituições</h2>
        <p>
            Sendo uma campanha de estoque limitado, pode ocorrer que, no momento da
            liberação ou do pagamento, um ou mais itens do carrinho estejam esgotados.
        </p>
        <p>
            Nessas situações, a Vésteme poderá:
        </p>
        <ul>
            <li>
                informar ao participante sobre a indisponibilidade e
                <strong>oferecer produtos similares</strong> (por exemplo, mesmo modelo em outra cor,
                peça equivalente em faixa de preço próxima ou outro item da mesma categoria);
            </li>
            <li>
                ajustar o valor final do pedido conforme os itens efetivamente aceitos;
            </li>
            <li>
                cancelar parcialmente o item indisponível, sem ônus adicional para o cliente,
                caso ele não tenha interesse na substituição sugerida.
            </li>
        </ul>
        <p>
            A aceitação de produtos substitutos é <strong>opcional</strong> ao cliente.
            Caso não haja substituição aceitável, o valor correspondente ao item indisponível
            não será cobrado, ou, se já cobrado, deverá ser estornado ou compensado conforme
            o meio de pagamento utilizado.
        </p>
    </section>

    <section>
        <h2>8. Formas de pagamento e condições comerciais</h2>
        <p>
            As principais formas de pagamento na campanha são:
        </p>
        <ul>
            <li><strong>Pix</strong>, com condição à vista;</li>
            <li>
                <strong>Cartão de crédito</strong>, com possibilidade de parcelamento,
                em especial em até <strong>3x</strong> e até <strong>12x</strong>, conforme
                regras do sistema de pagamento utilizado, operadora do cartão e valor do pedido.
            </li>
        </ul>
        <p>
            A Vésteme poderá, a seu critério e a depender dos meios de pagamento disponíveis,
            ajustar as opções de parcelamento, taxas de juros e eventuais encargos,
            sempre informando o cliente antes da conclusão do pagamento.
        </p>
        <p>
            <strong>Não há valor mínimo obrigatório de pedido</strong> definido pela Vésteme
            para participação na campanha, mas podem existir valores mínimos de parcela
            exigidos pela administradora do cartão ou pelo meio de pagamento utilizado.
        </p>
        <p>
            O <strong>frete não é gratuito</strong> nesta ação promocional. Os custos de envio
            são de responsabilidade do cliente, conforme tabela de frete, transportadora
            escolhida, região de entrega, peso e volume dos produtos, entre outros fatores
            logísticos.
        </p>
    </section>

    <section>
        <h2>9. Envio, prazos e política de trocas/devoluções</h2>
        <h3>9.1. Prazos de envio</h3>
        <p>
            Após a confirmação do pagamento, o prazo médio para preparação e envio dos pedidos
            da campanha “A Maior Black da Vésteme” será de <strong>3 a 5 dias úteis</strong>,
            podendo variar conforme:
        </p>
        <ul>
            <li>volume de pedidos recebidos;</li>
            <li>capacidade de expedição no período;</li>
            <li>localidade de entrega;</li>
            <li>eventos de força maior, greves ou circunstâncias alheias ao controle da Vésteme.</li>
        </ul>
        <p>
            O prazo de entrega estimado será informado de acordo com a transportadora
            escolhida e o endereço fornecido pelo cliente.
        </p>

        <h3>9.2. Trocas, devoluções e arrependimento</h3>
        <p>
            Por se tratar de uma ação promocional com descontos agressivos, a regra geral
            da campanha é que <strong>não haverá trocas ou devoluções por motivo de escolha
            de cor, tamanho ou arrependimento puramente comercial</strong>, especialmente
            para compras caracterizadas como aquisição para revenda, uso profissional
            ou com emissão em nome de pessoa jurídica (CNPJ).
        </p>
        <p>
            Entretanto, a Vésteme cumprirá integralmente a <strong>legislação aplicável
            de proteção ao consumidor</strong>, quando configurada relação de consumo,
            em especial:
        </p>
        <ul>
            <li>
                o direito de arrependimento em até <strong>7 (sete) dias</strong> contados
                da contratação ou do recebimento do produto, nos casos de vendas à distância
                para <strong>consumidores finais pessoa física</strong>, conforme previsto
                no Código de Defesa do Consumidor (CDC), quando aplicável;
            </li>
            <li>
                o dever de garantir reparo, troca ou opções legais em caso de
                <strong>produto com defeito</strong> (vício de qualidade), dentro dos
                prazos legais.
            </li>
        </ul>
        <p>
            Assim, mesmo na campanha, <strong>quaisquer cláusulas que limitem direitos
            mínimos assegurados por lei a consumidores finais serão interpretadas
            de acordo com a legislação vigente</strong>. Para compras que não se enquadrem
            como relação de consumo (por exemplo, vendas B2B para revenda), poderão
            prevalecer regras contratuais mais restritivas, desde que não contrariem
            a legislação aplicável àquela relação específica.
        </p>
        <p>
            Em caso de dúvida sobre trocas, devoluções ou exercício de direito de
            arrependimento, o cliente deverá entrar em contato pelos canais oficiais
            informados pela Vésteme, preferencialmente antes de qualquer envio de produtos,
            para receber orientações sobre o procedimento adequado.
        </p>
    </section>

    <section>
        <h2>10. Limites por cliente e análise antifraude</h2>
        <p>
            Não há, nesta edição, um limite pré-estabelecido de valor por pedido ou de
            quantidade máxima de peças/combos por CPF ou CNPJ. No entanto:
        </p>
        <ul>
            <li>
                todos os pedidos estão sujeitos à <strong>disponibilidade de estoque</strong>;
            </li>
            <li>
                a Vésteme poderá realizar <strong>análise antifraude</strong> e, se necessário,
                solicitar confirmação de dados ou documentos adicionais antes de liberar
                o envio ou efetivar a venda.
            </li>
        </ul>
        <p>
            Em situações de suspeita de fraude, uso indevido de dados, padrões atípicos
            de pedidos ou qualquer irregularidade, a Vésteme poderá cancelar ou reter o pedido
            até a completa apuração, sem prejuízo de comunicar autoridades competentes,
            se cabível.
        </p>
    </section>

    <section>
        <h2>11. Cancelamento de pedidos pela Vésteme</h2>
        <p>
            A Vésteme poderá cancelar total ou parcialmente pedidos da campanha,
            sem prejuízo de reembolso integral de valores eventualmente pagos, nas
            seguintes situações exemplificativas:
        </p>
        <ul>
            <li><strong>Suspeita de fraude</strong>, uso indevido de dados ou violação
                de normas de segurança;</li>
            <li><strong>Erro evidente de sistema</strong> ou falha operacional que resulte
                em valores manifestamente incorretos, condições inexequíveis ou divergências
                graves entre o anúncio e o produto;</li>
            <li><strong>Não pagamento</strong> dentro dos prazos estabelecidos no link
                de pagamento ou nas comunicações oficiais;</li>
            <li><strong>Impossibilidade logística</strong> decorrente de fatos alheios
                ao controle da Vésteme (por exemplo, greves, desastres naturais, mudanças
                abruptas em políticas de transporte), desde que comunicada ao cliente
                com a devida devolução de valores pagos, quando aplicável;</li>
            <li><strong>Descumprimento das regras desta campanha</strong> ou uso dos canais
                oficiais para fins indevidos, abusivos ou ilícitos.</li>
        </ul>
        <p>
            Sempre que possível, o cliente será comunicado sobre o motivo do cancelamento
            e as opções de reembolso ou remanejamento, conforme o caso.
        </p>
    </section>

    <section>
        <h2>12. Tratamento de dados pessoais</h2>
        <p>
