    <section>
        <h2>3. Público participante</h2>
        <p>
            Podem participar da campanha:
        </p>
        <ul>
            <li>
                <strong>Consumidores finais (varejo)</strong>, pessoas físicas maiores
                de 18 anos, com CPF válido, que adquiram produtos para uso próprio,
                familiar ou pessoal; e
            </li>
            <li>
                <strong>Lojistas, revendedores e profissionais do setor de moda</strong>,
                pessoas físicas ou jurídicas com CPF ou CNPJ, que adquiram para revenda
                ou uso ligado à atividade econômica.
            </li>
        </ul>
        <p>
            A Vésteme pode, ainda, permitir que um adulto realize compras em nome de
            terceiros (por exemplo, mãe comprando para filha), desde que os dados
            cadastrais e de responsabilidade do pedido sejam desse adulto.
        </p>
        <p>
            Não há restrição específica a colaboradores, parceiros ou familiares
            da Vésteme, que poderão participar nas mesmas condições gerais.
        </p>
    </section>

