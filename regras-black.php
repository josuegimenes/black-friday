            <li>
                <strong>WhatsApp oficial da Vésteme</strong>, incluindo grupos oficiais
                da Black, utilizado para comunicações sobre liberação, lembretes de pagamento
                e suporte.
            </li>
        </ul>
        <p>
            Em caso de dificuldades técnicas comprovadas, a Vésteme poderá, a seu critério,
            registrar pedidos ou interesses por outros meios (por exemplo, contato direto
            em redes sociais ou atendimentos específicos), sempre que operacionalmente
            viável. Nesses casos, a Vésteme se reserva o direito de analisar a situação
            individualmente, <strong>sem obrigação de aceitar ou de manter as mesmas
            prioridades de fila aplicáveis aos pedidos feitos pela landing page</strong>.
